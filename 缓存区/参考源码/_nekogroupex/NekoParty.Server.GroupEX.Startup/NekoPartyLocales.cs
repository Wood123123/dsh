	private void AddLocale(string language, Dictionary<string, string> values)
	{
		if (!localeTable.Global.TryGetValue(language, out var value))
		{
			logger.Warning("NekoParty locale '" + language + "' not found in SPT database, skipped.", (Exception)null);
			return;
		}
		_explicitLanguages.Add(language);
		value.AddTransformer((Func<GlobalLocaleDictionary, GlobalLocaleDictionary>)delegate(GlobalLocaleDictionary localeData)
		{
			foreach (KeyValuePair<string, string> value2 in values)
			{
				((Dictionary<string, string>)(object)localeData)[value2.Key] = value2.Value;
			}
			return localeData;
		});
	}

	private void ApplyEnglishFallbackToOtherLanguages()
	{
		if (_englishFallback == null)
		{
			return;
		}
		foreach (KeyValuePair<string, LazyLoad<GlobalLocaleDictionary>> item in localeTable.Global)
		{
			string key = item.Key;
			if (_explicitLanguages.Contains(key))
			{
				continue;
			}
			item.Value.AddTransformer((Func<GlobalLocaleDictionary, GlobalLocaleDictionary>)delegate(GlobalLocaleDictionary localeData)
			{
				foreach (KeyValuePair<string, string> item2 in _englishFallback)
				{
					if (!((Dictionary<string, string>)(object)localeData).ContainsKey(item2.Key))
					{
						((Dictionary<string, string>)(object)localeData)[item2.Key] = item2.Value;
					}
				}
				return localeData;
			});
		}
	}
